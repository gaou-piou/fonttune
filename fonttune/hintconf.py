"""fontconfig snippets for the built families: bytecode hinting (`--style
medium`, for fonts with ttfautohint hints) or no hinting at all (`--style none`,
the `nohint` setting: outlines drawn as designed, only anti-aliased, as macOS
draws them)."""
import sys
from pathlib import Path
from xml.sax.saxutils import escape

# At device scale 1 Chromium/Electron use linear advances only for hintslight
# or none, so hintmedium would round every glyph advance to a whole pixel.
CHROMIUM = ("chrome", "chromium", "brave", "helium", "electron", "code", "slack",
            "signal-desktop", "vesktop")
STYLES = ("medium", "none")


def families(fonts, style="medium"):
    """Families the snippet names. medium: only fonts that carry bytecode.
    Unhinted fonts would get no hinting at all under hinting=true/autohint=false,
    and variable fonts are hinted at their default instance only (other weights
    get distorted). none: every font, variable ones included (nothing runs)."""
    from fontTools.ttLib import TTFont

    from .cli import family
    out = set()
    for p in fonts:
        t = TTFont(p, lazy=True)
        if style == "medium" and ("fvar" in t or "fpgm" not in t or "prep" not in t):
            print(f"fonttune: hintconf: {Path(p).name}: "
                  f"{'variable font' if 'fvar' in t else 'no bytecode'}, left to the autohinter",
                  file=sys.stderr)
            continue
        fam = family(t)
        if fam:
            out.add(fam)
    return sorted(out)


def render(fams, name="fonttune", style="medium"):
    if style == "none":
        blocks = "".join(f"""  <match target="font">
    <test name="family" compare="eq"><string>{escape(f)}</string></test>
    <edit name="hintstyle" mode="assign"><const>hintnone</const></edit>
  </match>
""" for f in fams)
        about = """Draw these families without hinting
     (hintnone): the outlines as designed, only anti-aliased, as macOS draws
     them. Overrides the desktop's hint style for them, GTK4's built-in
     hintslight included (cairo takes the font's hintstyle). Chromium and
     Firefox read it too, and keep fractional advances. Stem darkening
     (FREETYPE_PROPERTIES) does not reach them: it belongs to the autofitter."""
    else:
        tests = "\n".join(
            f'    <test qual="all" name="prgname" compare="not_eq"><string>{p}</string></test>'
            for p in CHROMIUM)
        blocks = "".join(f"""  <match target="font">
    <test name="family" compare="eq"><string>{escape(f)}</string></test>
{tests}
    <edit name="hinting" mode="assign"><bool>true</bool></edit>
    <edit name="autohint" mode="assign"><bool>false</bool></edit>
    <edit name="hintstyle" mode="assign"><const>hintmedium</const></edit>
  </match>
""" for f in fams)
        about = """Use the ttfautohint bytecode of these fonts instead of
     FreeType's light autohinter. hintmedium, not hintfull: same rendering in
     cairo/pango, and Blink keeps subpixel positioning at hintmedium only.
     Chromium and Electron apps are excluded (see fonttune/hintconf.py)."""
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Generated by {escape(name)}. {about} -->
<fontconfig>
{blocks}</fontconfig>
"""


def main(fonts, out, name="fonttune", style="medium"):
    fams = families(fonts, style)
    if not fams:
        print("fonttune: hintconf: no hinted static fonts; the snippet changes nothing"
              if style == "medium" else "fonttune: hintconf: no family names found",
              file=sys.stderr)
    text = render(fams, name, style)
    if out == "-":
        sys.stdout.write(text)
    else:
        Path(out).parent.mkdir(parents=True, exist_ok=True)
        Path(out).write_text(text)
        print(f"fonttune: {len(fams)} families -> {out} (hint{style})")
