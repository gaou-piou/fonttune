"""fontconfig snippet that turns bytecode hinting on for the hinted families."""
import sys
from pathlib import Path
from xml.sax.saxutils import escape

# At device scale 1 Chromium/Electron use linear advances only for hintslight
# or none, so hintmedium would round every glyph advance to a whole pixel.
CHROMIUM = ("chrome", "chromium", "brave", "helium", "electron", "code", "slack",
            "signal-desktop", "vesktop")


def families(fonts):
    from fontTools.ttLib import TTFont
    out = set()
    for p in fonts:
        n = TTFont(p, lazy=True)["name"]
        for ids in ((16, 1),):
            for nid in ids:
                r = n.getName(nid, 3, 1, 0x409) or n.getName(nid, 1, 0, 0)
                if r:
                    out.add(r.toUnicode())
                    break
    return sorted(out)


def render(fams, name="fonttune"):
    tests = "\n".join(
        f'    <test qual="all" name="prgname" compare="not_eq"><string>{p}</string></test>'
        for p in CHROMIUM)
    blocks = "".join(f"""  <match target="font">
    <test name="family" compare="eq"><string>{escape(f)}</string></test>
{tests}
    <edit name="hinting" mode="assign"><bool>true</bool></edit>
    <edit name="autohint" mode="assign"><bool>false</bool></edit>
    <edit name="hintstyle" mode="assign"><const>hintmedium</const></edit>
    <edit name="rgba" mode="assign"><const>none</const></edit>
  </match>
""" for f in fams)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Generated by {name}. Use the ttfautohint bytecode of these fonts instead of
     FreeType's light autohinter. hintmedium, not hintfull: same rendering in
     cairo/pango, and Blink keeps subpixel positioning at hintmedium only.
     rgba none: grayscale antialiasing, no LCD sub-pixel colour fringes.
     Chromium and Electron apps are excluded (see fonttune/hintconf.py). -->
<fontconfig>
{blocks}</fontconfig>
"""


def main(fonts, out, name="fonttune"):
    fams = families(fonts)
    if not fams:
        sys.exit("fonttune: no family names found")
    text = render(fams, name)
    if out == "-":
        sys.stdout.write(text)
    else:
        Path(out).parent.mkdir(parents=True, exist_ok=True)
        Path(out).write_text(text)
        print(f"fonttune: {len(fams)} families -> {out}")
